/**
 * Раскладка первого экрана.
 *
 * На время сравнения вариантов страница умеет показать прежний геро:
 *   ?hero=split — текст и кадр в две равные колонки (как было);
 *   без параметра — кадр во всю ширину, текст над ним в две колонки.
 *
 * Подключён в <head> обычным <script>, а не модулем: модуль отложенный,
 * и страница успела бы моргнуть исходной раскладкой. Когда вариант
 * выберут, файл и параметр уходят вместе с проигравшими правилами.
 */
(function () {
  'use strict';

  var value = new URLSearchParams(window.location.search).get('hero');

  if (value === 'split') {
    document.documentElement.setAttribute('data-hero', 'split');
  }
})();
